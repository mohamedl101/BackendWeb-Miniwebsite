<h1>Onderhoud en Veiligheid</h1>
<p>Een goed onderhouden motor is niet alleen betrouwbaarder, maar ook veiliger. Hier zijn de belangrijkste tips.</p>

<div class="section">
    <h2>Regelmatig onderhoud</h2>
    <p>Voer bij elke 5.000–10.000 km een basisonderhoud uit:</p>
    <ul style="color:#ccc; line-height:2; padding-left:20px;">
        <li>Olie en oliefilter vervangen</li>
        <li>Kettingspanning en smering controleren</li>
        <li>Remvloeistof peil controleren</li>
        <li>Bandenspanning en -slijtage controleren</li>
        <li>Koplampen en richtingaanwijzers testen</li>
    </ul>
</div>

<div class="section">
    <h2>Veilig rijden</h2>
    <p>Veiligheid begint met de juiste uitrusting en rijhouding:</p>
    <ul style="color:#ccc; line-height:2; padding-left:20px;">
        <li>Draag altijd een goedgekeurde helm (ECE 22.06 of hoger)</li>
        <li>Motorjas, handschoenen en laarzen zijn essentieel</li>
        <li>Zorg voor zichtbaarheid: draag felle kleuren of retroreflector</li>
        <li>Houd voldoende afstand en rij voorspelbaar</li>
        <li>Vermijd blindehoeken van vrachtwagens</li>
    </ul>
</div>

<div class="section">
    <h2>Winterstalling</h2>
    <p>Wanneer je de motor voor de winter stalt:</p>
    <ul style="color:#ccc; line-height:2; padding-left:20px;">
        <li>Tank volledig vullen om roestvorming te voorkomen</li>
        <li>Accu ontkoppelen of op druppellader zetten</li>
        <li>Ketting reinigen en smeren</li>
        <li>Motor afdekken met een ademende hoes</li>
    </ul>
</div>

<div class="section">
    <h2>APK & Keuring</h2>
    <p>In België is een periodieke technische keuring (PTI) verplicht voor motorfietsen ouder dan 3 jaar. Zorg dat je lichten, remmen en uitlaat in orde zijn vóór de keuring.</p>
</div>
